#!/usr/bin/env python3
"""
Builds the site data from the publication lists:
  publications.yaml          appended to by the monthly fetcher PR, reviewed by humans
  publications-manual.yaml   hand-maintained only, for what the fetcher can't find

Run:  python3 tools/build_publications.py [OUT_DIR]     (default: docs/)

Writes OUT_DIR/publications.json (consumed by the site) and
OUT_DIR/publications.csv: build outputs, not committed. Also writes
publications.md, the list as Markdown tables, at the repo root. It is
committed so the list reads on GitHub, but machine-generated:
never edit it. CI (.github/workflows/pages.yml) runs this on every push to
main, deploys the site, and commits publications.md if it changed.
Requires PyYAML.
"""
import csv, json, datetime, pathlib, sys
import yaml

FIELDS = ["category", "title", "date", "authors", "url", "venue", "also"]
OPTIONAL = {"venue", "also"}  # venue: "AFT 2026", ..., or "preprint"; also: another version of the work
CATEGORIES = ["Academic Papers", "Flashbots Writings", "Flashbots Collective Forum Posts",
              "ethresear.ch Post", "Excalidraw"]  # publications.md section order

root = pathlib.Path(__file__).resolve().parent.parent
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / "docs"
out.mkdir(parents=True, exist_ok=True)

records = [r for name in ("publications.yaml", "publications-manual.yaml")
           for r in yaml.safe_load((root / name).read_text(encoding="utf-8")) or []]

# sanity checks: fail the build rather than publish a broken list
seen = set()
for r in records:
    assert set(FIELDS) - OPTIONAL <= set(r) <= set(FIELDS), f"wrong fields: {r}"
    for k in OPTIONAL:
        r[k] = str(r.get(k) or "")
    r["date"] = datetime.date.fromisoformat(str(r["date"])).isoformat()
    r["authors"] = r["authors"] or ""
    assert r["category"] in CATEGORIES, f"unknown category: {r}"
    for u in filter(None, (r["url"], r["also"])):
        assert u.startswith("http"), r
        assert u not in seen, f"duplicate url: {u}"
        seen.add(u)

records = [{k: r[k] for k in FIELDS} for r in records]
records.sort(key=lambda r: r["date"], reverse=True)

with open(out / "publications.json", "w", encoding="utf-8") as f:
    json.dump(records, f, ensure_ascii=False, indent=2)
    f.write("\n")

with open(out / "publications.csv", "w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=FIELDS)
    w.writeheader()
    w.writerows(records)

cell = lambda s: s.replace("|", "\\|")
md = ["<!-- Generated by tools/build_publications.py. Do not edit: edit publications.yaml or publications-manual.yaml. -->", "",
      "# Flashbots Research Publications", "",
      "Generated from [publications.yaml](https://github.com/flashbots/mev-research/blob/main/publications.yaml) and [publications-manual.yaml](https://github.com/flashbots/mev-research/blob/main/publications-manual.yaml)"
      " by `tools/build_publications.py`. **Read-only**: edit those, not this file, which is regenerated on every merge. Searchable at"
      " [research.flashbots.net](https://research.flashbots.net/), with the data as"
      " [JSON](https://research.flashbots.net/publications.json) and [CSV](https://research.flashbots.net/publications.csv).",
      "", "Authors tagged *(Flashbots)* are Flashbots-affiliated.", ""]
for cat in CATEGORIES:
    rows = [r for r in records if r["category"] == cat]
    md += [f"## {cat}", "", f"{len(rows)} entries.", "", "| Date | Title | Authors |", "| --- | --- | --- |"]
    md += [f"| {r['date']} | [{cell(r['title'])}]({r['url']})"
           + (f" · *{cell(r['venue'])}*" if r["venue"] not in ("", "preprint") else "")
           + (f" · [also]({r['also']})" if r["also"] else "")
           + f" | {cell(r['authors']) or '_not listed_'} |" for r in rows]
    md.append("")
(root / "publications.md").write_text("\n".join(md) + "\n", encoding="utf-8")

print(f"wrote {len(records)} records to {out}")
